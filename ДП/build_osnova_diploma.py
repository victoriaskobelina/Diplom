def pil_font(size: int, bold: bool = False) -> ImageFont.FreeTypeFont:
    candidates = [
        r"C:\Windows\Fonts\timesbd.ttf" if bold else r"C:\Windows\Fonts\times.ttf",
        r"C:\Windows\Fonts\arialbd.ttf" if bold else r"C:\Windows\Fonts\arial.ttf",
        r"C:\Windows\Fonts\calibrib.ttf" if bold else r"C:\Windows\Fonts\calibri.ttf",
    ]
    for path in candidates:
        if Path(path).exists():
            return ImageFont.truetype(path, size)
    return ImageFont.load_default()


def wrap(draw: ImageDraw.ImageDraw, text: str, fnt: ImageFont.FreeTypeFont, max_width: int) -> list[str]:
    lines: list[str] = []
    for raw in text.splitlines() or [""]:
        words = raw.split()
        current = ""
        for word in words:
            test = word if not current else f"{current} {word}"
            if draw.textbbox((0, 0), test, font=fnt)[2] <= max_width:
                current = test
            else:
                if current:
                    lines.append(current)
                current = word
        if current:
            lines.append(current)
    return lines


def draw_text_box(draw: ImageDraw.ImageDraw, box, text: str, fnt, fill: str = TEXT, center: bool = True):
    x1, y1, x2, y2 = box
    lines = wrap(draw, text, fnt, x2 - x1 - 24)
    line_h = fnt.size + 8
    y = y1 + max(10, ((y2 - y1) - line_h * len(lines)) / 2)
    for line in lines:
        bbox = draw.textbbox((0, 0), line, font=fnt)
        x = x1 + (x2 - x1 - (bbox[2] - bbox[0])) / 2 if center else x1 + 12
        draw.text((x, y), line, font=fnt, fill=fill)
        y += line_h


def rounded(draw, box, fill: str, outline: str = BLUE, width: int = 3, radius: int = 18):
    draw.rounded_rectangle(box, radius=radius, fill=fill, outline=outline, width=width)


def arrow(draw, start, end, fill: str = BLUE, width: int = 4):
    import math

    draw.line([start, end], fill=fill, width=width)
    angle = math.atan2(end[1] - start[1], end[0] - start[0])
    ah = 16
    p1 = (end[0] - ah * math.cos(angle - math.pi / 6), end[1] - ah * math.sin(angle - math.pi / 6))
    p2 = (end[0] - ah * math.cos(angle + math.pi / 6), end[1] - ah * math.sin(angle + math.pi / 6))
    draw.polygon([end, p1, p2], fill=fill)


