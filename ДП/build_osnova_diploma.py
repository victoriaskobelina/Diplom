def set_cell_shading(cell, fill: str):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill.replace("#", ""))


def set_cell_width(cell, width_cm: float):
    tc_pr = cell._tc.get_or_add_tcPr()
    tc_w = tc_pr.find(qn("w:tcW"))
    if tc_w is None:
        tc_w = OxmlElement("w:tcW")
        tc_pr.append(tc_w)
    tc_w.set(qn("w:w"), str(int(width_cm * 567)))
    tc_w.set(qn("w:type"), "dxa")


def format_paragraph(paragraph, *, bold=False, size=14, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=True):
    paragraph.alignment = align
    pf = paragraph.paragraph_format
    pf.line_spacing = 1.5
    pf.space_after = Pt(0)
    pf.space_before = Pt(0)
    pf.first_line_indent = Cm(1.25) if first_line else Cm(0)
    for run in paragraph.runs:
        run.font.name = "Times New Roman"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = RGBColor(0, 0, 0)


def format_table(table, widths: list[float] | None = None):
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    for row_i, row in enumerate(table.rows):
        for col_i, cell in enumerate(row.cells):
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            if widths and col_i < len(widths):
                set_cell_width(cell, widths[col_i])
            if row_i == 0:
                set_cell_shading(cell, BLUE_LIGHT)
            for p in cell.paragraphs:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER if row_i == 0 or (widths and widths[col_i] <= 2.0) else WD_ALIGN_PARAGRAPH.LEFT
                p.paragraph_format.first_line_indent = Cm(0)
                p.paragraph_format.line_spacing = 1.15
                p.paragraph_format.space_after = Pt(0)
                for run in p.runs:
                    run.font.name = "Times New Roman"
                    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
                    run.font.size = Pt(12)
                    run.font.bold = row_i == 0


class Inserter:
    def __init__(self, doc: Document, marker):
        self.doc = doc
        self.marker = marker

    def _move_before_marker(self, element):
        self.marker._p.addprevious(element)

    def page_break(self):
        p = self.doc.add_paragraph()
        p.add_run().add_break(WD_BREAK.PAGE)
        self._move_before_marker(p._p)

    def paragraph(self, text: str = "", *, bold=False, size=14, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_line=True):
        p = self.doc.add_paragraph()
        if text:
            p.add_run(text)
        format_paragraph(p, bold=bold, size=size, align=align, first_line=first_line)
        self._move_before_marker(p._p)
        return p

    def heading(self, text: str, level: int = 1):
        if level == 1:
            self.page_break()
        p = self.paragraph(
            text,
            bold=True,
            size=14,
            align=WD_ALIGN_PARAGRAPH.LEFT,
            first_line=False,
        )
        p.paragraph_format.space_after = Pt(6)
        return p

    def caption(self, text: str):
        p = self.paragraph(text, size=14, align=WD_ALIGN_PARAGRAPH.CENTER, first_line=False)
        p.paragraph_format.space_after = Pt(6)
        return p

    def picture(self, path: Path, width_cm: float, caption: str):
        p = self.doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run()
        run.add_picture(str(path), width=Cm(width_cm))
        format_paragraph(p, align=WD_ALIGN_PARAGRAPH.CENTER, first_line=False)
        self._move_before_marker(p._p)
        self.caption(caption)

    def table(self, data: list[list[str]], caption: str, widths: list[float] | None = None):
        self.paragraph(caption, align=WD_ALIGN_PARAGRAPH.LEFT, first_line=False)
        table = self.doc.add_table(rows=len(data), cols=len(data[0]))
        for i, row in enumerate(data):
            for j, value in enumerate(row):
                table.cell(i, j).text = value
        format_table(table, widths)
        self.marker._p.addprevious(table._tbl)
        self.paragraph("")
        return table


def find_appendix_marker(doc: Document):
    for p in doc.paragraphs:
        if p.text.strip() == "Приложение Б":
            return p
    raise RuntimeError("Не найден маркер 'Приложение Б'")


