def paragraph_text(p) -> str:
    return "".join(p.xpath(".//w:t/text()", namespaces=NS))


def replace_paragraph_text(p, text: str) -> None:
    p_pr = p.find("w:pPr", namespaces=NS)
    for child in list(p):
        if p_pr is not None and child is p_pr:
            continue
        p.remove(child)

    run = etree.Element(f"{{{NS['w']}}}r")
    t = etree.SubElement(run, f"{{{NS['w']}}}t")
    t.set("{http://www.w3.org/XML/1998/namespace}space", "preserve")
    t.text = text
    p.append(run)


def main():
    if not BACKUP.exists():
        shutil.copy2(DOCX, BACKUP)

    with ZipFile(DOCX, "r") as zin:
        entries = {item.filename: zin.read(item.filename) for item in zin.infolist()}

    root = etree.fromstring(entries["word/document.xml"])
    paragraphs = root.xpath(".//w:body/w:p", namespaces=NS)

    start = next(
        i
        for i, p in enumerate(paragraphs)
        if paragraph_text(p).strip() == "1.2 Анализ и формирование требований"
    )
    end = next(
        i
        for i, p in enumerate(paragraphs[start + 1 :], start + 1)
        if paragraph_text(p).strip().startswith("1.3")
    )

    section_paragraphs = [p for p in paragraphs[start + 1 : end] if paragraph_text(p).strip()]
    if len(section_paragraphs) != len(NEW_SECTION_TEXTS):
        raise RuntimeError(
            f"Ожидалось {len(NEW_SECTION_TEXTS)} абзацев раздела 1.2, найдено {len(section_paragraphs)}"
        )

    for p, text in zip(section_paragraphs, NEW_SECTION_TEXTS):
        replace_paragraph_text(p, text)

    entries["word/document.xml"] = etree.tostring(
        root, xml_declaration=True, encoding="UTF-8", standalone=True
    )

    tmp = DOCX.with_suffix(".tmp.docx")
    with ZipFile(tmp, "w", ZIP_DEFLATED) as zout:
        for name, data in entries.items():
            zout.writestr(name, data)
    tmp.replace(DOCX)

    print(DOCX)
    print(BACKUP)
    print(f"section_1_2_paragraphs={len(NEW_SECTION_TEXTS)}")


if __name__ == "__main__":
    main()
